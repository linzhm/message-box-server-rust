#[test]
fn profile_default_and_prefix_precedence_match_typescript_vectors() {
    let cases = [
        (snapshot(&[]), ResourceProfile::Standard),
        (
            snapshot(&[("RESOURCE_PROFILE", " small ")]),
            ResourceProfile::Small,
        ),
        (
            snapshot(&[
                ("RESOURCE_PROFILE", "small"),
                ("MESSAGE_BOX_RESOURCE_PROFILE", " HIGH-THROUGHPUT "),
            ]),
            ResourceProfile::HighThroughput,
        ),
        (
            snapshot(&[
                ("RESOURCE_PROFILE", "small"),
                ("MESSAGE_BOX_RESOURCE_PROFILE", " \u{FEFF} "),
            ]),
            ResourceProfile::Small,
        ),
    ];

    for (environment, expected) in cases {
        assert_eq!(
            ResourceConfig::from_snapshot(&environment).unwrap().profile,
            expected
        );
    }

    let global_empty = snapshot(&[("RESOURCE_PROFILE", " ")]);
    assert_eq!(
        ResourceConfig::from_snapshot(&global_empty)
            .unwrap_err()
            .to_string(),
        "MESSAGE_BOX_RESOURCE_PROFILE must be small, standard, or high-throughput"
    );
    let non_ecmascript_space = snapshot(&[("RESOURCE_PROFILE", "\u{0085}small\u{0085}")]);
    assert!(ResourceConfig::from_snapshot(&non_ecmascript_space).is_err());
}

#[test]
fn resource_limit_overrides_match_typescript_vectors() {
    let accepted = [
        ("-1", ResourceLimit::Unlimited),
        (" Unlimited ", ResourceLimit::Unlimited),
        (" 7 ", ResourceLimit::Finite(7)),
        (
            "9007199254740991",
            ResourceLimit::Finite(9_007_199_254_740_991),
        ),
    ];
    for (raw_value, expected) in accepted {
        let environment = snapshot(&[("MESSAGE_BOX_MAX_RECIPIENTS", raw_value)]);
        let config = ResourceConfig::from_snapshot(&environment).unwrap();
        assert_eq!(config.max_recipients, expected, "input {raw_value:?}");
    }

    let rejected = [
        (
            "0",
            "MESSAGE_BOX_MAX_RECIPIENTS must be -1, unlimited, or a positive integer",
        ),
        (
            "-2",
            "MESSAGE_BOX_MAX_RECIPIENTS must be -1, unlimited, or a positive integer",
        ),
        (
            "1.5",
            "MESSAGE_BOX_MAX_RECIPIENTS must be -1, unlimited, or a positive integer",
        ),
        (
            "1e3",
            "MESSAGE_BOX_MAX_RECIPIENTS must be -1, unlimited, or a positive integer",
        ),
        (
            "01",
            "MESSAGE_BOX_MAX_RECIPIENTS must be -1, unlimited, or a positive integer",
        ),
        (
            "9007199254740992",
            "MESSAGE_BOX_MAX_RECIPIENTS must not exceed 9007199254740991",
        ),
        (
            "18446744073709551616",
            "MESSAGE_BOX_MAX_RECIPIENTS must not exceed 9007199254740991",
        ),
    ];
    for (raw_value, expected_error) in rejected {
        let environment = snapshot(&[("MESSAGE_BOX_MAX_RECIPIENTS", raw_value)]);
        assert_eq!(
            ResourceConfig::from_snapshot(&environment)
                .unwrap_err()
                .to_string(),
            expected_error,
            "input {raw_value:?}"
        );
    }
}

#[test]
fn legacy_list_batch_size_matches_typescript_vectors_and_precedence() {
    let cases = [
        (
            snapshot(&[("MESSAGE_LIST_BATCH_SIZE", " 42 ")]),
            ResourceLimit::Finite(42),
            ResourceLimit::Finite(42),
        ),
        (
            snapshot(&[("MESSAGE_LIST_BATCH_SIZE", " Unlimited ")]),
            ResourceLimit::Unlimited,
            ResourceLimit::Unlimited,
        ),
        (
            snapshot(&[]),
            ResourceLimit::Finite(1_000),
            ResourceLimit::Finite(1_000),
        ),
        (
            snapshot(&[
                ("MESSAGE_LIST_BATCH_SIZE", "42"),
                ("MESSAGE_BOX_LIST_DEFAULT_LIMIT", "7"),
                ("MESSAGE_BOX_LIST_MAX_LIMIT", "8"),
            ]),
            ResourceLimit::Finite(7),
            ResourceLimit::Finite(8),
        ),
        (
            snapshot(&[("MESSAGE_BOX_RESOURCE_PROFILE", "small")]),
            ResourceLimit::Finite(250),
            ResourceLimit::Finite(500),
        ),
        (
            snapshot(&[("MESSAGE_BOX_RESOURCE_PROFILE", "high-throughput")]),
            ResourceLimit::Finite(1_000),
            ResourceLimit::Finite(5_000),
        ),
    ];

    for (environment, expected_default, expected_maximum) in cases {
        let config = ResourceConfig::from_snapshot(&environment).unwrap();
        assert_eq!(config.list_default_limit, expected_default);
        assert_eq!(config.list_max_limit, expected_maximum);
    }

    let invalid_legacy_with_overrides = snapshot(&[
        ("MESSAGE_LIST_BATCH_SIZE", "0"),
        ("MESSAGE_BOX_LIST_DEFAULT_LIMIT", "7"),
        ("MESSAGE_BOX_LIST_MAX_LIMIT", "8"),
    ]);
    assert_eq!(
        ResourceConfig::from_snapshot(&invalid_legacy_with_overrides)
            .unwrap_err()
            .to_string(),
        "MESSAGE_LIST_BATCH_SIZE must be -1, unlimited, or a positive integer"
    );

    let invalid_legacy = [
        (
            "0",
            "MESSAGE_LIST_BATCH_SIZE must be -1, unlimited, or a positive integer",
        ),
        (
            "-2",
            "MESSAGE_LIST_BATCH_SIZE must be -1, unlimited, or a positive integer",
        ),
        (
            "1.5",
            "MESSAGE_LIST_BATCH_SIZE must be -1, unlimited, or a positive integer",
        ),
        (
            "1e3",
            "MESSAGE_LIST_BATCH_SIZE must be -1, unlimited, or a positive integer",
        ),
        (
            "01",
            "MESSAGE_LIST_BATCH_SIZE must be -1, unlimited, or a positive integer",
        ),
        (
            "9007199254740992",
            "MESSAGE_LIST_BATCH_SIZE must be a safe integer",
        ),
    ];
    for (raw_value, expected_error) in invalid_legacy {
        let environment = snapshot(&[("MESSAGE_LIST_BATCH_SIZE", raw_value)]);
        assert_eq!(
            ResourceConfig::from_snapshot(&environment)
                .unwrap_err()
                .to_string(),
            expected_error,
            "input {raw_value:?}"
        );
    }
}

#[test]
fn profile_validation_and_cross_limit_constraints_match_typescript_vectors() {
    let invalid_profiles = [
        snapshot(&[("MESSAGE_BOX_RESOURCE_PROFILE", "huge")]),
        snapshot(&[("RESOURCE_PROFILE", " huge ")]),
    ];
    for environment in invalid_profiles {
        assert_eq!(
            ResourceConfig::from_snapshot(&environment)
                .unwrap_err()
                .to_string(),
            "MESSAGE_BOX_RESOURCE_PROFILE must be small, standard, or high-throughput"
        );
    }

    let invalid_pairs = [
        (
            "MESSAGE_BOX_LIST_DEFAULT_LIMIT",
            "MESSAGE_BOX_LIST_MAX_LIMIT",
            "MESSAGE_BOX_LIST_DEFAULT_LIMIT must not exceed MESSAGE_BOX_LIST_MAX_LIMIT",
        ),
        (
            "MESSAGE_BOX_DEVICE_LIST_DEFAULT_LIMIT",
            "MESSAGE_BOX_DEVICE_LIST_MAX_LIMIT",
            "MESSAGE_BOX_DEVICE_LIST_DEFAULT_LIMIT must not exceed MESSAGE_BOX_DEVICE_LIST_MAX_LIMIT",
        ),
        (
            "MESSAGE_BOX_PERMISSION_LIST_DEFAULT_LIMIT",
            "MESSAGE_BOX_PERMISSION_LIST_MAX_LIMIT",
            "MESSAGE_BOX_PERMISSION_LIST_DEFAULT_LIMIT must not exceed MESSAGE_BOX_PERMISSION_LIST_MAX_LIMIT",
        ),
    ];
    for (default_key, max_key, expected_error) in invalid_pairs {
        let environment = snapshot(&[(default_key, "101"), (max_key, "100")]);
        assert_eq!(
            ResourceConfig::from_snapshot(&environment)
                .unwrap_err()
                .to_string(),
            expected_error
        );
    }

    let unlimited_max = snapshot(&[
        ("MESSAGE_BOX_LIST_DEFAULT_LIMIT", "101"),
        ("MESSAGE_BOX_LIST_MAX_LIMIT", "-1"),
    ]);
    assert_eq!(
        ResourceConfig::from_snapshot(&unlimited_max)
            .unwrap()
            .list_max_limit,
        ResourceLimit::Unlimited
    );
    let unlimited_default = snapshot(&[
        ("MESSAGE_BOX_LIST_DEFAULT_LIMIT", "-1"),
        ("MESSAGE_BOX_LIST_MAX_LIMIT", "1"),
    ]);
    assert_eq!(
        ResourceConfig::from_snapshot(&unlimited_default)
            .unwrap()
            .list_default_limit,
        ResourceLimit::Unlimited
    );
}
