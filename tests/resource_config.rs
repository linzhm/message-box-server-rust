#[path = "../src/resource_config.rs"]
mod resource_config;

use resource_config::{EnvironmentSnapshot, ResourceConfig, ResourceLimit, ResourceProfile};

fn snapshot(values: &[(&str, &str)]) -> EnvironmentSnapshot {
    values
        .iter()
        .map(|(key, value)| ((*key).to_owned(), (*value).to_owned()))
        .collect()
}

fn ordered_limits(config: &ResourceConfig) -> [ResourceLimit; 28] {
    [
        config.max_message_body_bytes,
        config.max_recipients,
        config.list_default_limit,
        config.list_max_limit,
        config.list_max_offset,
        config.list_max_response_bytes,
        config.max_inbox_messages,
        config.max_inbox_bytes,
        config.max_sender_messages,
        config.max_sender_bytes,
        config.max_acknowledgment_ids,
        config.device_list_default_limit,
        config.device_list_max_limit,
        config.device_list_max_offset,
        config.max_notification_devices,
        config.notification_recipient_concurrency,
        config.fcm_send_concurrency,
        config.websocket_max_connections,
        config.websocket_max_connections_per_identity,
        config.websocket_max_rooms_per_connection,
        config.websocket_control_rate_limit,
        config.websocket_max_concurrent_sends,
        config.websocket_send_rate_limit,
        config.websocket_max_recipient_connections,
        config.permission_list_default_limit,
        config.permission_list_max_limit,
        config.permission_list_max_offset,
        config.retention_days,
    ]
}

